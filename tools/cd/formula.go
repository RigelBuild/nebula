package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// formulaHomepage is the project page each formula names.
const formulaHomepage = "https://github.com/RigelBuild/nebula"

var (
	errFormulaName   = errors.New("formula name must be a lowercase tool name")
	errFormulaSystem = errors.New("formula needs assets for known systems")
	toolName         = regexp.MustCompile(`^[a-z][a-z0-9]*(-[a-z0-9]+)*$`)
)

// formulaOrder fixes the order of systems in a formula: macOS, then Linux.
var formulaOrder = []string{"aarch64-darwin", "x86_64-linux", "aarch64-linux"}

// formulaBlock names the Homebrew OS and CPU blocks that hold one release system.
type formulaBlock struct{ osBlock, cpuBlock string }

var formulaBlocks = map[string]formulaBlock{
	"aarch64-darwin": {"on_macos", "on_arm"},
	"x86_64-linux":   {"on_linux", "on_intel"},
	"aarch64-linux":  {"on_linux", "on_arm"},
}

// writeFormulas writes Formula/<tool>.rb into outDir for every manifest package
// that has release assets. Packages without assets, such as non-binary tools,
// get no formula, and a Formula/<tool>.rb for a tool the manifest no longer
// releases is removed. It returns the written paths in name order.
func writeFormulas(manifestPath, outDir string) ([]string, error) {
	data, err := os.ReadFile(manifestPath)
	if err != nil {
		return nil, err
	}
	var m Manifest
	if err := json.Unmarshal(data, &m); err != nil {
		return nil, fmt.Errorf("decode manifest: %w", err)
	}
	var names []string
	for name, p := range m.Packages {
		// Homebrew needs an on_macos block, so a package with no darwin asset
		// gets no formula. Its Linux assets still ship in the Release.
		if _, darwin := p.Systems["aarch64-darwin"]; darwin {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return nil, err
	}
	// Drop formulae for tools no longer released, so the tap never keeps a stale one.
	keep := make(map[string]bool, len(names))
	for _, name := range names {
		keep[name+".rb"] = true
	}
	stale, err := filepath.Glob(filepath.Join(outDir, "*.rb"))
	if err != nil {
		return nil, err
	}
	for _, file := range stale {
		if !keep[filepath.Base(file)] {
			if err := os.Remove(file); err != nil {
				return nil, err
			}
		}
	}
	written := make([]string, 0, len(names))
	for _, name := range names {
		body, err := renderFormula(name, m.Packages[name])
		if err != nil {
			return nil, err
		}
		file := filepath.Join(outDir, name+".rb")
		if err := os.WriteFile(file, body, 0o644); err != nil {
			return nil, err
		}
		written = append(written, file)
	}
	return written, nil
}

// renderFormula returns the Homebrew formula for one released binary tool. Its
// url and sha256 are the manifest's per-system asset values, copied verbatim.
func renderFormula(name string, p Package) ([]byte, error) {
	if !toolName.MatchString(name) {
		return nil, fmt.Errorf("%w: %q", errFormulaName, name)
	}
	if len(p.Systems) == 0 {
		return nil, fmt.Errorf("%w: %s has no assets", errFormulaSystem, name)
	}
	for system := range p.Systems {
		if _, ok := formulaBlocks[system]; !ok {
			return nil, fmt.Errorf("%w: %s for %s", errFormulaSystem, system, name)
		}
	}
	var b strings.Builder
	b.WriteString("# frozen_string_literal: true\n\n")
	b.WriteString("# Generated by RigelBuild/nebula CD sync-out from release-manifest.json. Do not edit.\n")
	fmt.Fprintf(&b, "class %s < Formula\n", formulaClass(name))
	fmt.Fprintf(&b, "  desc %q\n", name+" from RigelBuild/nebula")
	fmt.Fprintf(&b, "  homepage %q\n", formulaHomepage)
	fmt.Fprintf(&b, "  version %q\n", p.Version)
	openOS := ""
	for _, system := range formulaOrder {
		asset, ok := p.Systems[system]
		if !ok {
			continue
		}
		block := formulaBlocks[system]
		if block.osBlock != openOS {
			if openOS != "" {
				b.WriteString("  end\n")
			}
			fmt.Fprintf(&b, "\n  %s do\n", block.osBlock)
			openOS = block.osBlock
		}
		fmt.Fprintf(&b, "    %s do\n", block.cpuBlock)
		fmt.Fprintf(&b, "      url %q\n", asset.URL)
		fmt.Fprintf(&b, "      sha256 %q\n", asset.SHA256)
		b.WriteString("    end\n")
	}
	b.WriteString("  end\n")
	// Release assets hold one top-level bin/ directory. Homebrew enters it before install.
	b.WriteString("\n  def install\n    bin.install Dir[\"*\"]\n  end\nend\n")
	return []byte(b.String()), nil
}

// formulaClass turns a tool name into its Ruby class name: length-gate is LengthGate.
func formulaClass(name string) string {
	var b strings.Builder
	for _, part := range strings.Split(name, "-") {
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}
